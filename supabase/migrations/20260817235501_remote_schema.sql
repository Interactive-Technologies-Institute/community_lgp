CREATE OR REPLACE FUNCTION public.auto_lock_post()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
  IF NEW.created_at < NOW() - INTERVAL '7 days' THEN
    NEW.is_locked := TRUE;
  END IF;
  RETURN NEW;
END;
$function$;
CREATE OR REPLACE FUNCTION public.check_islr_submission_vote_limit()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  vote_count int;
begin
  perform 1 from public.islr_submissions where id = new.submission_id for update;

  select count(*) into vote_count
  from public.islr_submission_votes
  where submission_id = new.submission_id;

  if vote_count >= 3 then
    raise exception 'Esta submissão já tem 3 votos.';
  end if;

  return new;
end;
$function$;
CREATE OR REPLACE FUNCTION public.get_closest_signs(query_array bigint[], limit_count integer, offset_count integer)
 RETURNS TABLE(id bigint, created_at timestamp with time zone, name text, video text, annotation jsonb, theme text[], is_anotated bigint, last_changed timestamp with time zone, description text, annotation_array bigint[], context_video text, sentence text, frequency bigint, theme_flattened text, district text)
 LANGUAGE plpgsql
 SET statement_timeout TO '10s'
AS $function$BEGIN

  RETURN QUERY
  WITH scored_signs AS (
    SELECT 
      s.id,
      s.created_at,
      s.name,
      s.video,
      s.annotation,
      s.theme,
      s.is_anotated,
      s.last_changed,
      s.description,
      s.annotation_array,
      s.context_video,
      s.sentence,
      s.frequency,
      s.theme_flattened,
      s.district,
      score_calc.score
    FROM signs s
    CROSS JOIN LATERAL (
      SELECT COALESCE(SUM(
        CASE
          WHEN s.annotation_array[qi] = 1 THEN
            5 *
            CASE qp.tipo
              WHEN 'configuracao' THEN 100
              WHEN 'localizacao' THEN 90
              WHEN 'movimento' THEN 80
              WHEN 'orientacao' THEN 70
              WHEN 'expressao facial' THEN 60
              ELSE 0
            END

          WHEN EXISTS (
            SELECT 1
            FROM generate_subscripts(s.annotation_array, 1) AS si
            JOIN parameters sp ON sp.id = si
            WHERE s.annotation_array[si] = 1
              AND qp.parent IS NOT NULL
              AND qp.parent <> ''
              AND sp.parent = qp.parent
              AND sp.code <> qp.code
          ) THEN
            3 *
            CASE qp.tipo
              WHEN 'configuracao' THEN 100
              WHEN 'localizacao' THEN 90
              WHEN 'movimento' THEN 80
              WHEN 'orientacao' THEN 70
              WHEN 'expressao facial' THEN 60
              ELSE 0
            END

          WHEN EXISTS (
            SELECT 1
            FROM generate_subscripts(s.annotation_array, 1) AS si
            JOIN parameters sp ON sp.id = si
            WHERE s.annotation_array[si] = 1
              AND sp.code = qp.parent
          ) THEN
            3 *
            CASE qp.tipo
              WHEN 'configuracao' THEN 100
              WHEN 'localizacao' THEN 90
              WHEN 'movimento' THEN 80
              WHEN 'orientacao' THEN 70
              WHEN 'expressao facial' THEN 60
              ELSE 0
            END

          WHEN EXISTS (
            SELECT 1
            FROM generate_subscripts(s.annotation_array, 1) AS si
            JOIN parameters sp ON sp.id = si
            WHERE s.annotation_array[si] = 1
              AND sp.code = ANY(qp.children)
          ) THEN
            3 *
            CASE qp.tipo
              WHEN 'configuracao' THEN 100
              WHEN 'localizacao' THEN 90
              WHEN 'movimento' THEN 80
              WHEN 'orientacao' THEN 70
              WHEN 'expressao facial' THEN 60
              ELSE 0
            END

          ELSE 0
        END
      ), 0) AS score
      FROM generate_subscripts(query_array, 1) AS qi
      JOIN parameters qp ON qp.id = qi
      WHERE query_array[qi] = 1
    ) score_calc
    WHERE CAST(s.is_anotated AS INTEGER) = 2
      AND COALESCE(s.theme_flattened, '') NOT ILIKE '%CEB%'
      AND COALESCE(s.theme_flattened, '') NOT ILIKE '%Filmar%'
  )

  SELECT
    ss.id,
    ss.created_at,
    ss.name,
    ss.video,
    ss.annotation,
    ss.theme,
    ss.is_anotated,
    ss.last_changed,
    ss.description,
    ss.annotation_array,
    ss.context_video,
    ss.sentence,
    ss.frequency,
    ss.theme_flattened,
    ss.district
  FROM scored_signs ss
  WHERE ss.score > 0
  ORDER BY ss.score DESC, ss.name ASC;

END;$function$;
