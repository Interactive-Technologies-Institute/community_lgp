CREATE OR REPLACE FUNCTION public.hamming_distance(array1 bigint[], array2 bigint[])
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
DECLARE
  distance INTEGER := 0;
BEGIN
  IF cardinality(array1) != cardinality(array2) THEN
    RAISE EXCEPTION 'Arrays must be of the same length';
  END IF;

  FOR i IN 1..cardinality(array1) LOOP
    IF array1[i] != array2[i] THEN
      distance := distance + 1;
    END IF;
  END LOOP;

  RETURN distance;
END;
$function$;
CREATE OR REPLACE FUNCTION public.handle_islr_submission_vote()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  vote_count int;
  approve_count int;
begin
  select count(*), count(*) filter (where approved)
  into vote_count, approve_count
  from public.islr_submission_votes
  where submission_id = new.submission_id;

  if vote_count >= 3 then
    update public.islr_submissions
    set status = case when approve_count > 1 then 'approved' else 'rejected' end
    where id = new.submission_id;
  end if;

  return new;
end;
$function$;
CREATE OR REPLACE FUNCTION public.handle_sign_moderation_updates()
 RETURNS trigger
